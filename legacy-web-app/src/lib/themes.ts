// Premium theme registry. Each theme defines a mode (dark/light) and a map of
// CSS variables that override the base tokens declared in src/styles.css.
// Themes are applied by writing the variables to :root via inline style.

export type ThemeMode = "dark" | "light";

export type ThemeDef = {
  id: string;
  name: string;
  mode: ThemeMode;
  description: string;
  // Preview swatches (bg, surface, accent)
  preview: { bg: string; surface: string; accent: string; text: string };
  // CSS variable overrides (raw values — usually oklch(...) or color())
  vars: Record<string, string>;
};

// Helper to keep theme definitions compact.
function dark(
  id: string,
  name: string,
  description: string,
  preview: ThemeDef["preview"],
  vars: Record<string, string>,
): ThemeDef {
  return { id, name, mode: "dark", description, preview, vars };
}
function light(
  id: string,
  name: string,
  description: string,
  preview: ThemeDef["preview"],
  vars: Record<string, string>,
): ThemeDef {
  return { id, name, mode: "light", description, preview, vars };
}

